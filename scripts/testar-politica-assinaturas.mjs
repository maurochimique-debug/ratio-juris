import assert from 'node:assert/strict';
import {authorizeSubscription} from '../server/subscription-policy.mjs';
const now=new Date('2026-11-14T12:00:00.000Z');
const account={userId:'user-1',emailVerified:true,disabled:false};
const valid={id:'subscription-1',userId:'user-1',status:'active',startsAt:'2026-11-10T00:00:00Z',endsAt:'2026-12-10T00:00:00Z',features:['simulador','questoes']};
const check=(a,s,f='simulador')=>authorizeSubscription({account:a,subscriptions:s,feature:f,now});
assert.equal(check(null,[valid]).reason,'login_required');
assert.equal(check({...account,emailVerified:false},[valid]).allowed,false);
assert.equal(check({...account,disabled:true},[valid]).allowed,false);
assert.equal(check(account,[]).reason,'subscription_required');
assert.equal(check(account,[{...valid,userId:'user-2'}]).allowed,false);
assert.equal(check(account,[{...valid,status:'pending'}]).allowed,false);
assert.equal(check(account,[{...valid,status:'canceled'}]).allowed,false);
assert.equal(check(account,[{...valid,status:'past_due'}]).allowed,false);
assert.equal(check(account,[{...valid,status:'refunded'}]).allowed,false);
assert.equal(check(account,[{...valid,endsAt:'2026-11-14T12:00:00Z'}]).allowed,false);
assert.equal(check(account,[{...valid,startsAt:'2026-11-15T00:00:00Z'}]).allowed,false);
assert.equal(check(account,[valid],'assistente-ia').reason,'feature_not_in_plan');
assert.equal(check(account,[valid]).allowed,true);
assert.equal(check(account,[{...valid,status:'trialing'}]).allowed,true);
console.log('PASS: 13 cenários da matriz de acesso');
